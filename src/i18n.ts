export type Translations = typeof en;

export function translations(settings: InsightSettings): Translations {
  const detected = (document.documentElement.lang || navigator.language || "en").toLowerCase();
  const locale = settings.locale === "auto" ? detected : settings.locale;
  return locale.startsWith("zh") ? zh : en;
}
